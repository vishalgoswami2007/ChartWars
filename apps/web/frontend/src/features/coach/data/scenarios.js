export const scenariosFor = (difficulty) => SCENARIOS.filter((s) => s.difficulty === difficulty);
export const getScenario = (id) => SCENARIOS.find((s) => s.id === id) ?? null;
export const playLength = (def, warmup) => def.segments.reduce((total, s) => total + s.len, 0) - warmup;